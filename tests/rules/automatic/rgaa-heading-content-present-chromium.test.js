'use strict';

/**
 * rgaa-heading-content-present in a real browser, where CSS-generated
 * content (::before, ::after) is computed.
 *
 * Skipped when Playwright or its Chromium build is not installed. Set
 * CHROMIUM_EXECUTABLE_PATH to use another Chromium build.
 */

const test = require('node:test');
const assert = require('node:assert/strict');
const fs = require('node:fs');

const { BROWSER_BUNDLE } = require('../../helpers/run.js');

const RULE_ID = 'rgaa-heading-content-present';

function page(body) {
  return `<!doctype html><html lang="en"><head><title>t</title></head><body><main>${body}</main></body></html>`;
}

let chromium;
try {
  ({ chromium } = require('playwright'));
} catch {
  chromium = null;
}
const executablePath = (() => {
  if (!chromium) return null;
  const candidates = [];
  try {
    candidates.push(chromium.executablePath());
  } catch {}
  if (process.env.CHROMIUM_EXECUTABLE_PATH) candidates.push(process.env.CHROMIUM_EXECUTABLE_PATH);
  return candidates.find((p) => p && fs.existsSync(p)) || null;
})();
const skip = !chromium
  ? 'playwright not installed'
  : !executablePath
    ? 'no Chromium build found (set CHROMIUM_EXECUTABLE_PATH)'
    : false;

// The summary quotes what the CSS generates: a text, or an icon font glyph
// by its code point.
test(`${RULE_ID} in Chromium: generated content is quoted`, { skip }, async (t) => {
  const browser = await chromium.launch({ executablePath });
  t.after(() => browser.close());
  const p = await browser.newPage();
  t.after(() => p.close());
  await p.setContent(
    page(
      '<style>.i::before{content:"\\f002"}.t::before{content:"Contact"}</style><h2 class="t"></h2><h2 class="i"></h2>'
    )
  );
  await p.addScriptTag({ content: BROWSER_BUNDLE });
  const result = await p.evaluate(
    (opts) => window.a11ycore.runa11yCoreInPage(null, null, opts, null),
    { rules: { include: RULE_ID } }
  );
  const [text, glyph] = result.checksResults.find((r) => r.ruleId === RULE_ID).occurrences;
  assert.equal(text.data.details.reasonCode, 'contentNotReadable');
  assert.equal(
    text.i18n.summaryKey,
    'headingContentPresent_summary_cantTell_contentNotReadable_generatedText'
  );
  assert.equal(
    text.summary,
    'This heading\'s only text, "Contact", is generated by CSS (::before, ::after): assistive technologies may not read it.'
  );
  assert.equal(
    glyph.i18n.summaryKey,
    'headingContentPresent_summary_cantTell_contentNotReadable_generatedGlyph'
  );
  assert.match(glyph.summary, /an icon font glyph \(U\+F002\) generated by CSS/);
});
