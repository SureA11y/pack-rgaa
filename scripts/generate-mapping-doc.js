'use strict';

/**
 * Generate docs/RGAA_MAPPING.md from rule-map.js: every
 * rule's RGAA tests with the reason for each, then every RGAA criterion with
 * the rules that speak to it, so a reviewer can check the mapping and a user
 * can see which criteria a scan never touches.
 *
 * Usage:
 *   node scripts/generate-mapping-doc.js           write the page
 *   node scripts/generate-mapping-doc.js --check   exit 1 if it is out of date
 */

const fs = require('fs');
const path = require('path');

const OUTPUT_FILE = path.join(__dirname, '..', 'docs', 'RGAA_MAPPING.md');

// A row's note, followed by the reason for each test it links outside RGAA's
// own WCAG correspondence.
function reasonOf(row) {
  const outside = row.outsideCorrespondence || {};
  const extra = Object.keys(outside).map((t) => `Exception for ${t}: ${outside[t]}`);
  return [row.note, ...extra].join(' ');
}

// Every test a row links: its tests, those it asks about, and those its
// findings or reason codes are sent to.
function linkedTests(row) {
  if (!row) return [];
  const routes = [...Object.values(row.reasonCodes || {}), ...(row.findings || [])];
  const all = new Set([...row.tests, ...(row.asks || [])]);
  for (const r of routes) for (const t of r.tests || []) all.add(t);
  return [...all];
}

// How a row links a test: by its findings only, asked about, or outside RGAA's
// correspondence.
function testLabel(row, t) {
  const marks = [];
  if ((row.asks || []).includes(t)) marks.push('asks');
  else if (!row.tests.includes(t)) marks.push('some findings');
  if (t in (row.outsideCorrespondence || {})) marks.push('exception');
  return marks.length ? `${t} (${marks.join(', ')})` : t;
}

function cell(text) {
  return String(text).replace(/\|/g, '\\|').replace(/\s+/g, ' ').trim();
}

function renderDoc({ rules, versions, themes, criteria, tests, ruleTests }) {
  const out = [];
  out.push('# RGAA mapping');
  out.push('');
  out.push(
    '<!-- GENERATED by scripts/generate-mapping-doc.js from rule-map.js; do not edit by hand. -->'
  );
  out.push('');
  out.push(
    "RGAA's criteria and tests are quoted from DINUM's RGAA 4.1.2 ([source](https://github.com/DISIC/accessibilite.numerique.gouv.fr), criteria last updated 7 January 2026), under the [Licence Ouverte 2.0](https://www.etalab.gouv.fr/licence-ouverte-open-licence/). The mapping is this pack's, not DINUM's; this pack is not affiliated with or endorsed by DINUM or the French State."
  );
  out.push('');
  out.push(
    "Which RGAA tests each rule checks, and which rules speak to each RGAA criterion. A scan names these tests on its results when asked (`engineOptions.mappings: ['rgaa']`, see [`ENGINE_OPTIONS.md`](https://github.com/SureA11y/core/blob/main/docs/ENGINE_OPTIONS.md#other-standards-mappings) in core); the notes below say how the mapping is made."
  );
  out.push('');
  out.push(
    '> **Review status:** drafted from the RGAA test wording, official methodology and glossary, then checked row by row against them; not yet reviewed by an RGAA auditor. Corrections go in `rule-map.js`; this page is regenerated from it.'
  );
  out.push('');
  out.push(
    'A rule maps to a test when its failure (or, for a manual rule, the question it raises) is direct evidence about what the test\'s methodology checks. A rule that fails is linked only when its usual failures really fail the test; where that is uncertain, the test is left off or the rule asks. A mapped rule covers the test in part at most: a `pass` never means an RGAA test is conforme, and most tests need a human. A test marked "(exception)" is linked although RGAA relates it to other WCAG criteria than the rule; the reason follows the note. Where a rule\'s findings fail different tests, each finding counts toward its own (by its text size, its list, its role…), and a criterion\'s result names only the tests of the findings that decided it; the note says how. A test marked "(asks)" is one where the rule\'s failures are only questions, and one marked "(some findings)" is one only some of its findings count toward.'
  );

  // A row's tests and those its reason codes send findings to.
  const linkedTests = (row) => {
    if (!row) return [];
    if (!row.reasonCodes) return row.tests;
    const all = new Set(row.tests);
    for (const c of Object.values(row.reasonCodes || {})) {
      for (const t of (c && c.tests) || []) all.add(t);
    }
    return [...all].sort((a, b) => a.localeCompare(b, 'en', { numeric: true }));
  };
  // Where each reason code's findings go, for the rule's row.
  const codesNote = (row) =>
    Object.entries((row && row.reasonCodes) || {})
      .map(([code, c]) => {
        const list = c && Array.isArray(c.tests) ? c.tests : row.tests;
        const where = list.length ? list.join(', ') : 'no test';
        return `\`${code}\`: ${where}${c && c.outcome === 'cantTell' ? ', asked (cantTell)' : ''}`;
      })
      .join('; ');

  for (const { version } of versions) {
    const table = ruleTests[version] || {};
    const mapped = rules.filter((r) => linkedTests(table[r.ruleId]).length);
    const reached = new Set(
      mapped.flatMap((r) => linkedTests(table[r.ruleId]).map((t) => tests[version][t].criterion))
    );
    const allCriteria = Object.keys(criteria[version]);

    out.push('');
    out.push(`## RGAA ${version}`);
    out.push('');
    out.push(
      `${mapped.length} of ${rules.length} rules map to at least one test; they reach ${reached.size} of ${allCriteria.length} criteria.`
    );

    out.push('');
    out.push('### By rule');
    out.push('');
    out.push('| Rule | Type | WCAG | RGAA tests | Why |');
    out.push('|---|---|---|---|---|');
    for (const r of rules) {
      const row = table[r.ruleId];
      const outside = (row && row.outsideCorrespondence) || {};
      const linked = linkedTests(row);
      const testList = linked.length
        ? linked.map((t) => (t in outside ? `${t} (exception)` : t)).join(', ')
        : '—';
      const codes = codesNote(row);
      const why = row
        ? reasonOf(row) + (codes ? ` By reason code: ${codes}.` : '')
        : 'Not mapped yet.';
      out.push(
        `| \`${r.ruleId}\` | ${r.type} | ${r.wcagSc.join(', ') || '—'} | ${testList} | ${cell(why)} |`
      );
    }

    out.push('');
    out.push('### By criterion');
    out.push('');
    for (const theme of themes[version]) {
      out.push(`#### ${theme.number}. ${theme.title}`);
      out.push('');
      out.push('| Criterion | Rules |');
      out.push('|---|---|');
      for (const [id, c] of Object.entries(criteria[version])) {
        if (c.theme !== theme.number) continue;
        const byTest = c.tests
          .map((t) => {
            const who = mapped.filter((r) => linkedTests(table[r.ruleId]).includes(t));
            return who.length ? `${t}: ${who.map((r) => `\`${r.ruleId}\``).join(', ')}` : null;
          })
          .filter(Boolean);
        out.push(`| **${id}** ${cell(c.title)} | ${byTest.length ? byTest.join('<br>') : '—'} |`);
      }
      out.push('');
    }
  }
  return out.join('\n').replace(/\n+$/, '\n');
}

function collect() {
  const core = require('@surea11y/core');
  const { RGAA_VERSIONS, RGAA_THEMES, RGAA_CRITERIA, RGAA_TESTS } = require('../map');
  const { RGAA_RULE_TESTS } = require('../rule-map');
  return {
    rules: core
      .getChecksCatalog({ packs: [require('..')] })
      .map((r) => ({ ruleId: r.ruleId, type: r.type, wcagSc: r.wcagSc }))
      .sort((a, b) => a.ruleId.localeCompare(b.ruleId)),
    versions: RGAA_VERSIONS,
    themes: RGAA_THEMES,
    criteria: RGAA_CRITERIA,
    tests: RGAA_TESTS,
    ruleTests: RGAA_RULE_TESTS
  };
}

async function format(source, file) {
  const prettier = require('prettier');
  const options = (await prettier.resolveConfig(file)) || {};
  return prettier.format(source, { ...options, filepath: file });
}

async function build() {
  const data = collect();
  return {
    [OUTPUT_FILE]: await format(renderDoc(data), OUTPUT_FILE)
  };
}

async function main() {
  const pages = await build();
  const check = process.argv.includes('--check');
  let stale = false;
  for (const [file, expected] of Object.entries(pages)) {
    const rel = path.relative(process.cwd(), file);
    if (check) {
      const actual = fs.existsSync(file) ? fs.readFileSync(file, 'utf8') : '';
      if (actual !== expected) {
        console.error(`[generate-rgaa-mapping-doc] ${rel} is out of date; run npm run mapping-doc`);
        stale = true;
      }
    } else {
      fs.writeFileSync(file, expected, 'utf8');
      console.log(`[generate-rgaa-mapping-doc] wrote ${rel}`);
    }
  }
  if (stale) process.exit(1);
  if (check) console.log('[generate-rgaa-mapping-doc] up to date');
}

module.exports = { renderDoc, collect, build };

if (require.main === module) {
  main().catch((e) => {
    console.error(e);
    process.exit(1);
  });
}
