'use strict';

/**
 * @check rgaa-link-content-label-present
 * @atomic true
 * @summary A link must have text or an image text alternative in its content
 * @standard RGAA 4.1.2 (no WCAG Success Criterion)
 * @applicability
 *   Applies to links included in the accessibility tree: <a> with an href
 *   (or, in SVG, an xlink:href), and elements with role="link". An <a href>
 *   whose role is another widget (role="button", role="tab") is not a link
 *   to assistive technologies and is not matched. <area> is not matched:
 *   RGAA judges its text alternative under 1.1.2. A page with no link is
 *   notApplicable.
 * @expectation
 *   The content of the link holds text, or an image with a text alternative
 *   (alt, aria-label, aria-labelledby, title, or the <title> or <text> of
 *   an <svg>). RGAA 6.2.1 asks for "un intitulé entre <a> et </a>", and
 *   its methodology checks that the content of the element contains a label
 *   ("texte ou alternative"). A name given only by aria-label,
 *   aria-labelledby or title on the link itself does not count: the RGAA
 *   glossary "Intitulé (ou nom accessible) de lien", Note 4, says a link
 *   with no content fails 6.2. An image that has no text alternative, or
 *   that is hidden with aria-hidden="true", gives the link no label; a
 *   <canvas>, or an <object> or <embed> of an image type, counts as an
 *   image, and its alternative is an aria-label, aria-labelledby, title or
 *   fallback text (glossary « Image porteuse d'information », note 1: the
 *   alternative of a link's only image is the link's label). Text added
 *   by CSS (::before, ::after) is not content between <a> and </a>
 *   (glossary « Intitulé de lien », note 5): a link whose only content is
 *   generated text fails (generatedTextOnly). The rule asks instead of
 *   failing when the content holds an embedded element such as a form
 *   field, or an element named by its own aria-label, or when text hidden
 *   from assistive technologies (aria-hidden="true") sits beside a name
 *   from aria-label, aria-labelledby or title. Hidden text with no such
 *   name leaves the link with no label at all, and fails.
 * @implementation-notes
 * - The content is read in the flat tree (helpers.flatChildNodes): text in a
 *   web component's shadow root, or slotted into it, is the link's content.
 * - Content inside hidden, display:none or visibility:hidden elements is not
 *   content: nobody sees or hears it.
 * - CSS-generated text is read from the computed ::before and ::after
 *   content, only where the page has a layout (a browser). jsdom does not
 *   compute it, so there a link whose only content is generated fails as
 *   a link with no content (noContentLabel or nameOutsideContent).
 * - Opt-in (tag `rgaa`): WCAG accepts any accessible name, which
 *   link-name-present checks, so the rule runs only under the rgaa-4.1.2
 *   profile, the `rgaa` tag or its own id.
 */

const id = 'rgaa-link-content-label-present';

const meta = {
  title: 'Links have a label in their content',
  description:
    'Checks that each link holds text or an image with a text alternative, rather than being named only by aria-label, aria-labelledby or title.',
  i18n: {
    titleKey: 'linkContentLabelPresent_title',
    descriptionKey: 'linkContentLabelPresent_description'
  },
  helpUrl: null,
  tags: ['rgaa', 'links', 'name', 'atomic', 'automatic'],
  wcagSc: [],
  normativeMappings: [],
  defaultSeverity: 'serious',
  category: 'operable',
  type: 'automatic',
  defaultConfidence: 'high',
  coverage: {},
  // The reason codes the rule gives, so definePack can check that `review`
  // names only these.
  reasonCodes: ['contentNotReadable', 'generatedTextOnly', 'nameOutsideContent', 'noContentLabel'],
  // How a person answers each question the rule asks, per reason code: a few
  // steps from the element the finding names, then what they see if it
  // passes and if it fails. In English; reports show it as "How to check".
  review: {
    contentNotReadable: {
      steps: [
        'Find the link the report names and look at what is between its opening and closing tags.',
        'Note what its content holds: an embedded element such as a form field, an element named by its own aria-label, or text hidden with aria-hidden="true" beside a name the link takes from aria-label, aria-labelledby or title.',
        "Read the link's content in the code and in the browser's accessibility inspector, and check whether the markup between its tags gives it a label that assistive technologies read: text, or an image with a text alternative."
      ],
      passWhen:
        "The markup between the link's opening and closing tags gives it a label that assistive technologies read: text, or an image with a text alternative. Text generated by CSS (::before, ::after) does not count (glossary « Intitulé de lien », note 5).",
      failWhen:
        "Nothing in the markup between the link's tags gives it a label assistive technologies read: its name comes only from CSS-generated text, from attributes, or from nothing, which fails RGAA 6.2.1."
    }
  }
};

function runInPage(ctx) {
  const dom = ctx.helpers.dom;
  const { document, window, helpers, rule } = ctx;
  const win = window || (document && dom.defaultView(document)) || null;

  function norm(s) {
    return String(s == null ? '' : s)
      .replace(/\s+/g, ' ')
      .trim();
  }

  function attr(el, name) {
    try {
      return dom.getAttribute(el, name);
    } catch {
      return null;
    }
  }

  function firstKnownRole(el) {
    const tokens = String(attr(el, 'role') || '')
      .trim()
      .toLowerCase()
      .split(/\s+/)
      .filter(Boolean);
    if (!tokens.length) return '';
    if (!helpers.aria || typeof helpers.aria.isKnownRole !== 'function') return tokens[0];
    for (const t of tokens) {
      try {
        if (helpers.aria.isKnownRole(t)) return t;
      } catch {}
    }
    return '';
  }

  function styleOf(el, pseudo) {
    if (!win || typeof win.getComputedStyle !== 'function') return null;
    try {
      return win.getComputedStyle(el, pseudo || null);
    } catch {
      return null;
    }
  }

  function isNotRendered(el) {
    if (dom.get(el, 'hasAttribute') && dom.hasAttribute(el, 'hidden')) return true;
    const cs = styleOf(el);
    return !!(cs && cs.display === 'none');
  }

  function isVisibilityHidden(el) {
    const cs = el ? styleOf(el) : null;
    return !!(cs && (cs.visibility === 'hidden' || cs.visibility === 'collapse'));
  }

  // Pseudo-element styles are read only where the page has a layout: jsdom
  // does not compute them, and reports each attempt as not implemented.
  function hasLayout() {
    const probe = dom.documentElement(document) || dom.body(document) || null;
    if (!probe || typeof dom.get(probe, 'getClientRects') !== 'function') return false;
    try {
      const rects = dom.getClientRects(probe);
      return !!(rects && rects.length > 0);
    } catch {
      return false;
    }
  }
  const pseudoSupported = hasLayout();

  // The first CSS-generated content found, for the summary: { text } or,
  // for an icon font glyph (a private use character), { glyph: 'U+F002' }.
  let firstGenerated = null;
  function hasGeneratedContent(el) {
    if (!pseudoSupported) return false;
    for (const pseudo of ['::before', '::after']) {
      const cs = styleOf(el, pseudo);
      const c = cs ? String(cs.content || '').trim() : '';
      if (!c || c === 'none' || c === 'normal' || c === '""' || c === "''") continue;
      if (!firstGenerated) {
        const quoted = [];
        c.replace(/"((?:[^"\\]|\\.)*)"|'((?:[^'\\]|\\.)*)'/g, (m, a, b) => {
          quoted.push(a != null ? a : b);
          return m;
        });
        const value = (quoted.length ? quoted.join('') : c).replace(/\s+/g, ' ').trim();
        const chars = [...value];
        const privateUse = (ch) => {
          const cp = ch.codePointAt(0);
          return (cp >= 0xe000 && cp <= 0xf8ff) || cp >= 0xf0000;
        };
        if (chars.length && chars.every(privateUse)) {
          firstGenerated = {
            glyph: chars
              .slice(0, 3)
              .map((ch) => `U+${ch.codePointAt(0).toString(16).toUpperCase()}`)
              .join(' ')
          };
        } else if (value) {
          firstGenerated = { text: value.length > 40 ? `${value.slice(0, 39)}…` : value };
        }
      }
      return true;
    }
    return false;
  }

  function idRefText(el, value) {
    const parts = [];
    for (const ref of String(value || '')
      .split(/\s+/)
      .filter(Boolean)) {
      let target = null;
      try {
        target = helpers.getElementByIdInTree(el, ref);
      } catch {}
      if (target) parts.push(norm(dom.textContent(target)));
    }
    return norm(parts.join(' '));
  }

  function tagOf(el) {
    return String(dom.localName(el) || dom.tagName(el) || '').toLowerCase();
  }

  function isImage(el) {
    const tag = tagOf(el);
    if (tag === 'img' || tag === 'svg') return true;
    if (tag === 'input') return String(attr(el, 'type') || '').toLowerCase() === 'image';
    return firstKnownRole(el) === 'img';
  }

  // The image's text alternative, per the RGAA glossary "Alternative
  // textuelle (image)"; for <svg>, its <title> child and <text> content too.
  function imageAlternative(el) {
    const tag = tagOf(el);
    const aria = idRefText(el, attr(el, 'aria-labelledby')) || norm(attr(el, 'aria-label'));
    if (aria) return aria;
    if (tag === 'img' || tag === 'input') {
      return norm(attr(el, 'alt')) || norm(attr(el, 'title'));
    }
    if (tag === 'svg') {
      const parts = [];
      for (const child of [...dom.querySelectorAll(el, ':scope > *')]) {
        if (tagOf(child) === 'title') parts.push(norm(dom.textContent(child)));
      }
      for (const t of [
        ...(dom.get(el, 'querySelectorAll') ? dom.querySelectorAll(el, 'text') : [])
      ]) {
        parts.push(norm(dom.textContent(t)));
      }
      return norm(parts.join(' '));
    }
    return '';
  }

  const EMBEDDED = new Set([
    'iframe',
    'frame',
    'video',
    'audio',
    'input',
    'select',
    'textarea',
    'meter',
    'progress',
    'object',
    'embed',
    'canvas'
  ]);

  // The children as rendered (the flat tree): a shadow host shows its
  // shadow root, and a <slot> the nodes assigned to it, or its fallback
  // content when none are.
  function renderedChildren(node) {
    try {
      const shadow = dom.nodeType(node) === 1 ? dom.shadowRoot(node) : null;
      if (shadow) return [...(dom.childNodes(shadow) || [])];
      if (dom.nodeType(node) === 1 && tagOf(node) === 'slot') {
        const assigned = [...(dom.assignedNodes(node, { flatten: true }) || [])];
        if (assigned.length) return assigned;
      }
    } catch {}
    return [...(dom.childNodes(node) || [])];
  }

  function analyse(root) {
    const found = {
      text: false,
      alternative: false,
      hiddenText: false,
      unlabelledImage: false,
      generated: false,
      embedded: false,
      descendantAriaName: false
    };
    firstGenerated = null;
    if (hasGeneratedContent(root)) found.generated = true;

    // Children as the page renders them: a shadow host's shadow root, a
    // <slot>'s assigned nodes, so a label inside a web component counts.
    function childrenOf(node) {
      if (helpers && typeof helpers.flatChildNodes === 'function') {
        try {
          return [...(helpers.flatChildNodes(node) || [])];
        } catch {}
      }
      return [...(dom.childNodes(node) || [])];
    }

    const clip = (t, max) => {
      const v = norm(t);
      return v.length > max ? `${v.slice(0, max - 1)}…` : v;
    };

    // `atHidden` is the aria-hidden="true" element the walk is under, if any.
    // What hides or replaces the label is kept, for the message: the first
    // hidden text, image with no alternative, embedded element, named
    // descendant and empty icon element.
    function walk(node, atHidden, depth) {
      if (depth > 200) return;
      for (const child of childrenOf(node)) {
        if (dom.nodeType(child) === 3) {
          if (!norm(child.data)) continue;
          const parent = dom.parentElement(child);
          if (isVisibilityHidden(parent)) {
            if (!found.notRendered && parent) {
              found.notRendered = {
                text: clip(dom.textContent(parent), 60),
                element: tagOf(parent),
                property: 'visibility: hidden',
                hiddenAttribute: false
              };
            }
            continue;
          }
          if (atHidden) {
            found.hiddenText = true;
            if (!found.ariaHiddenAt) {
              found.ariaHiddenAt = {
                text: clip(dom.textContent(atHidden), 60),
                element: tagOf(atHidden)
              };
            }
          } else found.text = true;
          continue;
        }
        if (dom.nodeType(child) !== 1) continue;
        const tag = tagOf(child);
        if (tag === 'script' || tag === 'style' || tag === 'template' || tag === 'desc') continue;
        if (tag === 'title') {
          // The <title> child of an SVG link is part of its label.
          const text = norm(dom.textContent(child));
          if (text) {
            if (atHidden) found.hiddenText = true;
            else found.text = true;
          }
          continue;
        }
        if (isNotRendered(child)) {
          const text = norm(dom.textContent(child));
          if (text && !found.notRendered) {
            found.notRendered = {
              text: clip(text, 60),
              element: tag,
              property: 'display: none',
              hiddenAttribute: !!(
                dom.get(child, 'hasAttribute') && dom.hasAttribute(child, 'hidden')
              )
            };
          }
          continue;
        }
        const hidden =
          atHidden || (String(attr(child, 'aria-hidden') || '').trim() === 'true' ? child : null);
        if (!hidden && hasGeneratedContent(child)) found.generated = true;

        if (isImage(child)) {
          if (hidden) continue;
          if (imageAlternative(child)) found.alternative = true;
          else {
            found.unlabelledImage = true;
            if (!found.imageAt) {
              found.imageAt = {
                element: tag,
                emptyAlt: tag === 'img' && attr(child, 'alt') != null
              };
            }
          }
          continue;
        }
        if (EMBEDDED.has(tag)) {
          if (tag === 'input' && String(attr(child, 'type') || '').toLowerCase() === 'hidden') {
            continue;
          }
          if (!hidden) {
            const alt =
              norm(attr(child, 'aria-label')) ||
              norm(attr(child, 'aria-labelledby')) ||
              norm(attr(child, 'title'));
            // A <canvas>, or an <object> or <embed> of an image type, is an
            // image: with no alternative, it labels nothing.
            const image =
              tag === 'canvas' ||
              ((tag === 'object' || tag === 'embed') &&
                /^image\//i.test(String(attr(child, 'type') || '').trim()));
            if ((tag === 'object' || tag === 'embed' || tag === 'canvas') && alt) {
              found.alternative = true;
            } else if (image) {
              found.unlabelledImage = true;
            } else {
              found.embedded = true;
              if (!found.embeddedAt) found.embeddedAt = { element: tag };
            }
          }
          if (tag === 'object' || tag === 'canvas') walk(child, hidden, depth + 1);
          continue;
        }
        if (!hidden && (norm(attr(child, 'aria-label')) || norm(attr(child, 'aria-labelledby')))) {
          found.descendantAriaName = true;
          if (!found.namedAt) {
            const label = norm(attr(child, 'aria-label'));
            found.namedAt = {
              element: tag,
              attribute: label ? 'aria-label' : 'aria-labelledby',
              name: clip(label || idRefText(child, attr(child, 'aria-labelledby')), 60)
            };
          }
        }
        if (!hidden && !found.emptyIcon) {
          const className = clip(attr(child, 'class'), 40);
          if (
            className &&
            !norm(dom.textContent(child)) &&
            !childrenOf(child).some((n) => dom.nodeType(n) === 1)
          ) {
            found.emptyIcon = { element: tag, className };
          }
        }
        walk(child, hidden, depth + 1);
      }
    }

    walk(root, null, 0);
    found.generatedAt = firstGenerated;
    return found;
  }

  function isLink(el) {
    const tag = tagOf(el);
    const role = firstKnownRole(el);
    if (tag === 'a' && (dom.hasAttribute(el, 'href') || dom.hasAttribute(el, 'xlink:href'))) {
      // A focusable link keeps its role under none/presentation.
      return !role || role === 'link' || role === 'none' || role === 'presentation';
    }
    return role === 'link';
  }

  function isIncluded(el) {
    const r = helpers.isIncludedInAccessibilityTree
      ? helpers.isIncludedInAccessibilityTree(el, ctx)
      : helpers.isAccTreeEligible
        ? helpers.isAccTreeEligible(el, ctx)
        : true;
    return typeof r === 'boolean' ? r : !!(r && r.eligible);
  }

  const selector = 'a, [role]';
  const nodes = helpers.queryAllSmart
    ? helpers.queryAllSmart(selector)
    : helpers.queryAll(selector);

  const fails = [];
  const questions = [];
  let applicableCount = 0;
  const seen = new Set();

  for (const el of nodes) {
    if (!el || !dom.get(el, 'getAttribute') || seen.has(el)) continue;
    seen.add(el);
    if (!isLink(el) || !isIncluded(el)) continue;
    applicableCount += 1;

    const found = analyse(el);
    if (found.text || found.alternative) continue;

    const eligInfo = helpers.getEligibilityInfo
      ? helpers.getEligibilityInfo(el, ctx, { targetSet: 'acc' })
      : null;
    const visibilityFilter = eligInfo || { targetSet: 'acc', accEligible: null, reasons: [] };

    let source = '';
    if (idRefText(el, attr(el, 'aria-labelledby'))) source = 'aria-labelledby';
    else if (norm(attr(el, 'aria-label'))) source = 'aria-label';
    else if (norm(attr(el, 'title'))) source = 'title';

    // Hidden text with no name at all leaves the link with no label for
    // anyone using assistive technologies, which fails. Text generated by
    // CSS is no content between <a> and </a> (glossary « Intitulé de lien »,
    // note 5): when it is all the link holds, the link fails.
    if (found.embedded || found.descendantAriaName || (found.hiddenText && source)) {
      const evidence = {
        reasonCode: 'contentNotReadable',
        hiddenText: found.hiddenText,
        generated: found.generated,
        embedded: found.embedded,
        descendantAriaName: found.descendantAriaName
      };
      // Which content keeps the label from assistive technologies, when the
      // walk found it.
      let variant = null;
      let params = {};
      if (found.hiddenText && source && found.ariaHiddenAt) {
        variant = 'ariaHiddenText';
        params = { ...found.ariaHiddenAt, source };
      } else if (found.namedAt) {
        variant = 'descendantName';
        params = found.namedAt;
      } else if (found.embeddedAt) {
        variant = 'embedded';
        params = found.embeddedAt;
      }
      const summaries = {
        ariaHiddenText: `This link's text "${params.text}" is in the <${params.element}> element with aria-hidden="true", so assistive technologies read only its ${params.source}, not text between <a> and </a>.`,
        descendantName: `This link has no text of its own: its only label is the ${params.attribute} "${params.name}" of the <${params.element}> element inside it.`,
        embedded: `This link holds an embedded <${params.element}>, and no text or image text alternative that assistive technologies read.`
      };
      questions.push(
        helpers.reportOccurrence(el, {
          summary: variant
            ? summaries[variant]
            : 'This link has content but no text or image text alternative that assistive technologies read: hidden text, an embedded element, or an element named by aria-label.',
          hint: 'Check whether the link content gives it a label. Put the link text inside the link, or give its image a text alternative.',
          i18n: {
            summaryKey: variant
              ? `linkContentLabelPresent_summary_cantTell_contentNotReadable_${variant}`
              : 'linkContentLabelPresent_summary_cantTell_contentNotReadable',
            hintKey: 'linkContentLabelPresent_hint_cantTell_contentNotReadable',
            params
          },
          uncertainty: {
            code: 'judgement-required',
            needed: 'Whether the link content that is not plain text gives the link a label.',
            evidence
          },
          data: { details: evidence, visibilityFilter }
        })
      );
      continue;
    }

    if (found.generated) {
      // What the CSS generates: a text, quoted, or an icon font glyph.
      const gen = found.generatedAt || {};
      const genVariant = gen.glyph ? 'glyph' : gen.text ? 'text' : '';
      fails.push(
        helpers.reportOccurrence(el, {
          summary: gen.glyph
            ? `The only content of this link is an icon font glyph (${gen.glyph}) generated by CSS (::before, ::after), which is not a label between <a> and </a>.`
            : gen.text
              ? `The only content of this link is the text "${gen.text}" generated by CSS (::before, ::after), which is not a label between <a> and </a>.`
              : 'The only content of this link is text generated by CSS (::before, ::after), which is not a label between <a> and </a>.',
          hint: 'Put the link text in the markup between <a> and </a>, or an image with a text alternative. Text generated by CSS does not count as link content (RGAA 6.2.1, glossary « Intitulé de lien », note 5).',
          i18n: {
            summaryKey: `linkContentLabelPresent_summary_fail_generatedTextOnly${genVariant ? `_${genVariant}` : ''}`,
            hintKey: 'linkContentLabelPresent_hint_fail_generatedTextOnly',
            params: gen.glyph ? { glyph: gen.glyph } : gen.text ? { text: gen.text } : {}
          },
          data: {
            details: {
              reasonCode: 'generatedTextOnly',
              ...(genVariant ? { generated: gen } : {}),
              nameSource: source || null,
              hiddenText: found.hiddenText,
              unlabelledImage: found.unlabelledImage
            },
            visibilityFilter
          }
        })
      );
      continue;
    }

    // What hides the label, or stands where it should be, when the walk
    // found it: the hint names it.
    let cause = null;
    if (found.notRendered) cause = { cause: 'hiddenText', params: found.notRendered };
    else if (found.ariaHiddenAt) cause = { cause: 'ariaHiddenText', params: found.ariaHiddenAt };
    else if (found.imageAt && found.imageAt.element === 'svg') {
      cause = { cause: 'svgNoName', params: {} };
    } else if (found.imageAt) cause = { cause: 'imageNoAlt', params: found.imageAt };
    else if (found.emptyIcon) cause = { cause: 'emptyIcon', params: found.emptyIcon };
    const p = cause ? cause.params : {};
    const causeHints = {
      hiddenText: `Its text "${p.text}" is in the <${p.element}> element with ${p.hiddenAttribute ? 'the hidden attribute' : p.property}, which hides it from screen readers as well as from view, so the link has no label. Let screen readers read it (a visually-hidden class keeps it off screen but read).`,
      ariaHiddenText: `Its text "${p.text}" is in the <${p.element}> element with aria-hidden="true", which hides it from screen readers, so the link has no label. Remove aria-hidden from that element.`,
      imageNoAlt: `Its content is the <${p.element}> element, with ${p.emptyAlt ? 'an empty alt, which marks it as decorative' : 'no text alternative'}, so the link has no label. Give the image a text alternative that says where the link goes.`,
      svgNoName:
        'Its content is an <svg> with no <title>, aria-label or aria-labelledby, so the link has no label. Give the <svg> role="img" and an aria-label that says where the link goes, or put text in the link.',
      emptyIcon: `Its content is an empty <${p.element} class="${p.className}">, probably an icon drawn by CSS, which gives no text, so the link has no label. Put text in the link, visually hidden if need be, that says where it goes.`
    };

    fails.push(
      helpers.reportOccurrence(el, {
        summary: source
          ? `This link has no text or image text alternative in its content; its name comes only from ${source}.`
          : 'This link has no text or image text alternative in its content.',
        hint: cause
          ? causeHints[cause.cause]
          : 'Put the link text inside the link, or an image with a text alternative. A name given only by aria-label, aria-labelledby or title does not count for RGAA 6.2.',
        i18n: {
          summaryKey: source
            ? 'linkContentLabelPresent_summary_fail_nameOutsideContent'
            : 'linkContentLabelPresent_summary_fail_noLabel',
          hintKey: cause
            ? `linkContentLabelPresent_hint_fail_${cause.cause}`
            : 'linkContentLabelPresent_hint_fail',
          params: { source, ...p }
        },
        data: {
          details: {
            reasonCode: source ? 'nameOutsideContent' : 'noContentLabel',
            nameSource: source || null,
            unlabelledImage: found.unlabelledImage,
            ...(cause ? { contentCause: cause.cause } : {})
          },
          visibilityFilter
        }
      })
    );
  }

  if (applicableCount === 0) {
    return { ruleId: rule.ruleId, outcome: 'notApplicable', severity: 'minor', occurrences: [] };
  }
  return {
    ruleId: rule.ruleId,
    ...helpers.resolveTieredOutcome(fails, questions, rule.defaultSeverity || 'serious')
  };
}

module.exports = { id, meta, runInPage };
